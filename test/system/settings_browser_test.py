"""Real Rails rendered QA. See docs/design-system/components.md for invocation.
Uses an isolated test DB/session prepared outside production; no passwords.
"""
import argparse
import json
from pathlib import Path
from playwright.sync_api import sync_playwright

parser = argparse.ArgumentParser()
parser.add_argument('--state', required=True)
parser.add_argument('--output', required=True)
parser.add_argument('--origin', default='http://127.0.0.1:3138')
parser.add_argument('--chromium', required=True)
args = parser.parse_args()
state = json.loads(Path(args.state).read_text())
output = Path(args.output)
output.mkdir(parents=True, exist_ok=True)
checks = []
errors = []

def check(condition, message):
    assert condition, message
    checks.append(message)

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=args.chromium, headless=True, args=['--disable-gpu', '--no-sandbox'])
    context = browser.new_context()
    context.add_cookies([{'name': 'session_token', 'value': state['cookie'], 'url': args.origin}])
    page = context.new_page()
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.set_default_timeout(10000)
    for width in [1280, 390, 320]:
        page.set_viewport_size({'width': width, 'height': 900})
        for section in ['domains', 'storage', 'env']:
            page.goto(args.origin + state['base'] + '/' + section)
            page.locator('[data-controller="row-actions"]').first.wait_for()
            page.wait_for_function('window.Stimulus && [...document.querySelectorAll("[data-controller= row-actions]")].every(e => window.Stimulus.getControllerForElementAndIdentifier(e,"row-actions"))')
            check(page.evaluate('document.documentElement.scrollWidth <= innerWidth'), f'{width} {section}: no horizontal overflow')
            add = page.locator('[data-ui-component="page-header"] .config-action-primary').first
            check(add.bounding_box()['height'] == (32 if width > 640 else 44), f'{width} {section}: primary geometry')
            trigger = page.locator('[data-row-actions-target="trigger"]').first
            box = trigger.bounding_box()
            check(box['width'] == box['height'] == 32, f'{width} {section}: visible icon square')
            check(trigger.evaluate('(e)=>getComputedStyle(e).padding') == '0px', f'{width} {section}: explicit icon padding independent of glyphs')
            svg = trigger.locator('svg').bounding_box()
            check(svg['width'] == svg['height'] == 16, f'{width} {section}: icon 16px')
            if width <= 640:
                hit = trigger.evaluate('(e) => { const s=getComputedStyle(e,"::after");return [s.top,s.right,s.bottom,s.left] }')
                check(hit == ['-6px'] * 4, f'{width} {section}: expanded 44px hit area')
                page.mouse.click(box['x'] - 4, box['y'] + 16)
                check(trigger.get_attribute('aria-expanded') == 'true', f'{width} {section}: expanded hit area clickable')
                page.keyboard.press('Escape')
            trigger.focus()
            trigger.press('Enter')
            menu = page.locator('[data-row-actions-target="menu"]:popover-open')
            menu.wait_for(state='visible')
            check(page.evaluate('document.activeElement.getAttribute("role") == "menuitem"'), f'{width} {section}: Enter focuses first visible item')
            check(menu.locator('[role="menuitem"]').first.evaluate('(e)=>getComputedStyle(e).justifyContent') == 'flex-start', f'{width} {section}: consistent left-aligned menu actions')
            menu_box = menu.bounding_box()
            check(menu_box['x'] >= 0 and menu_box['x'] + menu_box['width'] <= width and menu_box['y'] >= 0 and menu_box['y'] + menu_box['height'] <= 900, f'{width} {section}: top-layer menu in viewport')
            page.screenshot(path=str(output / f'{section}-{width}-menu.png'), full_page=True, animations='disabled')
            page.keyboard.press('End')
            check(page.evaluate('document.activeElement === [...document.querySelector(":popover-open").querySelectorAll("[role=menuitem]")].at(-1)'), f'{width} {section}: End focus')
            page.keyboard.press('Home')
            page.keyboard.press('ArrowDown')
            page.keyboard.press('ArrowUp')
            page.keyboard.press('Escape')
            check(trigger.get_attribute('aria-expanded') == 'false' and trigger.evaluate('(e)=> e===document.activeElement'), f'{width} {section}: Escape restores focus and aria')
            trigger.press('Space')
            check(trigger.get_attribute('aria-expanded') == 'true', f'{width} {section}: Space opens native trigger')
            page.locator('h1').click()
            check(trigger.get_attribute('aria-expanded') == 'false', f'{width} {section}: outside click closes')
            add.click()
            dialog = page.locator('dialog[open]')
            dialog.wait_for(state='visible')
            cancel = dialog.locator('.config-modal-footer button', has_text='Cancel')
            submit = dialog.locator('.config-modal-footer button[type="submit"]')
            check(cancel.bounding_box()['height'] == 32, f'{width} {section}: restrained Cancel')
            check(submit.bounding_box()['height'] == (32 if width > 640 else 44), f'{width} {section}: submit geometry')
            close = dialog.locator('[aria-label="Close dialog"]')
            check(close.bounding_box()['height'] == close.bounding_box()['width'] == 32, f'{width} {section}: close geometry')
            if width <= 640:
                cb, sb = cancel.bounding_box(), submit.bounding_box()
                check(cb['x'] + cb['width'] + 6 <= sb['x'], f'{width} {section}: footer tap areas do not overlap')
            page.screenshot(path=str(output / f'{section}-{width}-modal.png'), full_page=True, animations='disabled')
            cancel.click()
            check(page.locator('dialog[open]').count() == 0, f'{width} {section}: Cancel closes native dialog')
            page.screenshot(path=str(output / f'{section}-{width}.png'), full_page=True, animations='disabled')
        page.goto(args.origin + state['base'] + '/settings')
        forms = page.locator('.config-settings-form')
        check(forms.count() == 3, f'{width} General: three independent forms')
        boxes = [forms.nth(i).bounding_box() for i in range(3)]
        check(len(set(round(b['width']) for b in boxes)) == 1, f'{width} General: same form widths')
        for form in [forms.nth(i) for i in range(3)]:
            check(form.locator('button[type="submit"]').bounding_box()['height'] == (32 if width > 640 else 44), f'{width} General: scoped Save geometry')
        check(page.evaluate('document.documentElement.scrollWidth <= innerWidth'), f'{width} General: no overflow')
        page.screenshot(path=str(output / f'general-{width}.png'), full_page=True, animations='disabled')
    page.set_viewport_size({'width': 390, 'height': 900})
    page.goto(args.origin + state['base'] + '/env')
    row = page.locator('[data-controller="secret-field clipboard"]', has=page.locator('code', has_text='UI_EXAMPLE'))
    trigger = row.locator('[data-row-actions-target="trigger"]')
    trigger.click()
    row.get_by_role('menuitem', name='Reveal value').click()
    check(row.locator('[data-secret-field-target="display"]').inner_text() == 'example-only', 'Reveal is scoped to UI_EXAMPLE')
    check(page.locator('[data-secret-field-target="display"]', has_text='second-example').count() == 0, 'Other row remains masked')
    trigger.click()
    row.get_by_role('menuitem', name='Hide value').click()
    check(row.locator('[data-secret-field-target="display"]').inner_text() == '••••••••', 'Hide masks the same row')
    page.evaluate('Object.defineProperty(navigator,"clipboard",{configurable:true,value:{writeText:async()=>{throw new Error("denied")}}})')
    trigger.click()
    row.get_by_role('menuitem', name='Copy value').click()
    check(row.locator('[role="status"]').inner_text().startswith('Copy failed.'), 'Copy failure is announced honestly')
    check(trigger.get_attribute('aria-expanded') == 'false', 'Copy closes the menu')
    page.evaluate('Object.defineProperty(navigator,"clipboard",{configurable:true,value:{writeText:async text=>{window.copiedExample=text}}})')
    trigger.click()
    row.get_by_role('menuitem', name='Copy value').click()
    page.wait_for_function('window.copiedExample === "example-only"')
    check(row.locator('[role="status"]').inner_text() == 'Value copied.', 'Copy success follows clipboard resolution')
    trigger.click()
    row.get_by_role('menuitem', name='Edit Variable').click()
    dialog = page.locator('dialog[open]')
    dialog.wait_for(state='visible')
    check(dialog.locator('input[name="env_variable[name]"]').get_attribute('readonly') is not None, 'Lazy Edit preserves readonly name')
    dialog.locator('.config-modal-footer button[type="submit"]').click()
    page.wait_for_function('!document.querySelector("dialog[open]")')
    check(row.count() == 1, 'Lazy Edit successful save replaces collection and closes native dialog')
    row.locator('[data-row-actions-target="trigger"]').click()
    row.get_by_role('menuitem', name='Edit Variable').click()
    dialog.wait_for(state='visible')
    dialog.locator('.config-modal-footer button', has_text='Cancel').click()
    requests = []
    page.on('request', lambda request: requests.append(request.method))
    page.once('dialog', lambda dialog: dialog.dismiss())
    trigger.click()
    row.get_by_role('menuitem', name='Delete Variable').click()
    page.wait_for_timeout(100)
    check('DELETE' not in requests and row.count() == 1, 'Cancelled explicit variable confirmation sends no delete')
    # Turbo replaces an open row: native top layer and Stimulus listeners must not leak.
    trigger.click()
    row.evaluate('(e)=>{const clone=e.cloneNode(true);clone.querySelector("[aria-expanded]").setAttribute("aria-expanded","false");Turbo.renderStreamMessage(`<turbo-stream action="replace" target="${e.id}"><template>${clone.outerHTML}</template></turbo-stream>`)}')
    page.wait_for_timeout(100)
    check(page.locator(':popover-open').count() == 0, 'Turbo replacement removes an open top-layer menu')
    row.locator('[data-row-actions-target="trigger"]').click()
    check(page.locator(':popover-open').count() == 1, 'Replacement row reconnects exactly one working menu')
    page.keyboard.press('Escape')
    check(page.locator(':popover-open').count() == 0, 'Replacement menu closes with Escape')
    page.goto(args.origin + state['base'] + '/storage')
    trigger = page.locator('[data-row-actions-target="trigger"]').first
    trigger.click()
    page.locator(':popover-open [role="menuitem"]').first.click()
    dialog = page.locator('dialog[open]')
    dialog.wait_for(state='visible')
    check(dialog.locator('input[name="storage_mount[restart]"]').is_checked() is False, 'Storage action restart remains local and unchecked')
    check(dialog.locator('.restart-option').bounding_box()['height'] >= 44, 'Storage restart label has real 44px mobile target')
    dialog.locator('.config-modal-footer button', has_text='Cancel').click()
    check(page.locator('dialog[open]').count() == 0, 'Storage action Cancel closes exact native dialog')
    check(not errors, 'No JavaScript page errors: ' + repr(errors))
    browser.close()
(output / 'browser-checks.json').write_text(json.dumps({'checks': checks, 'count': len(checks), 'errors': errors}, indent=2))
print(f'{len(checks)} rendered browser checks passed')
